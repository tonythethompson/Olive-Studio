/**
 * Generates src/data/olive-recipes-catalog.ts from microsoft/olive-recipes (main).
 * Run: node scripts/generate-olive-recipes-catalog.mjs
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src/data/olive-recipes-catalog.ts");

const REPO = "microsoft/olive-recipes";
const BRANCH = "main";

const EXCLUDE_PATH = /(^\.|\/\.|eval_latency|config_schema|parameter_template|model_list|checks\.json|sample\.json|evaluator\.json|\/builtin\/|\/genai_lib\/)/;

const PROVIDER_DEVICE = {
  cpu: "CPU",
  cuda: "CUDA",
  webgpu: "CPU",
  nvtensorrtrtx: "TensorRT",
  tensorrt: "TensorRT",
  trt: "TensorRT",
  qnn: "QNN",
  qairt: "QNN",
  vitisai: "OpenVINO",
  openvino: "OpenVINO",
  aitk: "DirectML",
  dml: "DirectML",
  directml: "DirectML",
  olive: "CPU",
  cli: "CPU",
  baseline: "CPU",
  rocm: "CUDA",
  migraphx: "CUDA",
  oci: "CPU",
};

function inferArchitecture(modelFolder) {
  const n = modelFolder.toLowerCase();
  if (n.includes("whisper") || n.includes("moonshine")) return "Whisper";
  if (n.includes("llama") || n.includes("falcon") || n.includes("mistral") || n.includes("gemma") || n.includes("smollm")) return "Llama";
  if (n.includes("phi")) return "Phi";
  if (n.includes("qwen")) return "Qwen";
  if (n.includes("bert")) return "BERT";
  if (n.includes("mobilenet")) return "MobileNet";
  if (n.includes("resnet")) return "ResNet";
  if (n.includes("stable-diffusion") || n.includes("stable_diffusion") || n.includes("latentsync")) return "Stable Diffusion";
  if (n.includes("clip") || n.includes("vit")) return "MobileNet";
  return "Other";
}

function inferDevice(providerFolder) {
  const key = providerFolder.replace(/[^a-z0-9]/gi, "").toLowerCase();
  for (const [prefix, device] of Object.entries(PROVIDER_DEVICE)) {
    if (key === prefix || key.includes(prefix)) {
      return device;
    }
  }
  return "CPU";
}

function buildName(modelFolder, providerFolder, fileName) {
  const base = fileName.replace(/\.json$/i, "");
  return `${modelFolder} · ${providerFolder} · ${base}`;
}

function buildDescription(modelFolder, providerFolder, fileName) {
  return `Official microsoft/olive-recipes run config for ${modelFolder} (${providerFolder}/${fileName}).`;
}

async function fetchTree() {
  const url = `https://api.github.com/repos/${REPO}/git/trees/${BRANCH}?recursive=1`;
  const res = await fetch(url, { headers: { "User-Agent": "olive-studio-catalog-generator" } });
  if (!res.ok) {
    throw new Error(`GitHub tree fetch failed: ${res.status} ${res.statusText}`);
  }
  const data = await res.json();
  return data.tree.filter((e) => e.type === "blob" && e.path.endsWith(".json") && !EXCLUDE_PATH.test(e.path));
}

function escapeTs(str) {
  return str.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

async function main() {
  const blobs = await fetchTree();
  const entries = [];

  for (const blob of blobs) {
    const parts = blob.path.split("/");
    if (parts.length < 2) continue;

    const modelFolder = parts[0];
    const providerFolder = parts.length >= 3 ? parts[1] : "root";
    const fileName = parts[parts.length - 1];

    entries.push({
      name: buildName(modelFolder, providerFolder, fileName),
      architecture: inferArchitecture(modelFolder),
      device: inferDevice(providerFolder),
      repoPath: blob.path,
      description: buildDescription(modelFolder, providerFolder, fileName),
      metadataSource: "folder",
    });
  }

  entries.sort((a, b) => a.repoPath.localeCompare(b.repoPath));

  const lines = [
    "/* eslint-disable */",
    "// AUTO-GENERATED by scripts/generate-olive-recipes-catalog.mjs — do not edit by hand.",
    `// Source: https://github.com/${REPO} @ ${BRANCH} (${entries.length} recipes)`,
    "",
    'import type { RecipeCatalogItem } from "@/lib/oliveRecipeHub";',
    "",
    `export const OLIVE_RECIPES_REPO = "${REPO}" as const;`,
    `export const OLIVE_RECIPES_BRANCH = "${BRANCH}" as const;`,
    "",
    "export const OLIVE_RECIPES_CATALOG: RecipeCatalogItem[] = [",
  ];

  for (const e of entries) {
    lines.push("  {");
    lines.push(`    name: "${escapeTs(e.name)}",`);
    lines.push(`    architecture: "${escapeTs(e.architecture)}",`);
    lines.push(`    device: "${escapeTs(e.device)}",`);
    lines.push(`    repoPath: "${escapeTs(e.repoPath)}",`);
    lines.push(`    description: "${escapeTs(e.description)}",`);
    lines.push(`    metadataSource: "${escapeTs(e.metadataSource)}",`);
    lines.push("  },");
  }

  lines.push("];", "");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"), "utf-8");
  console.log(`Wrote ${entries.length} recipes to ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
